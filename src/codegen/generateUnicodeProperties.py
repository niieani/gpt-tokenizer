#!/usr/bin/env python3
"""Generate tokenizer character classes from the pinned Unicode 16 UCD.

Download https://www.unicode.org/Public/16.0.0/ucd/UnicodeData.txt, then run:
python3 src/codegen/generateUnicodeProperties.py --unicode-data /path/UnicodeData-16.txt --unicode17-data /path/UnicodeData-17.txt
The source data is licensed under Unicode License V3:
https://www.unicode.org/license.txt
"""
import argparse
import hashlib
from pathlib import Path

SOURCE_URL = 'https://www.unicode.org/Public/16.0.0/ucd/UnicodeData.txt'
EXPECTED_SHA256 = 'ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f'


def category_ranges(text):
    result = []
    pending = None
    for row in text.splitlines():
        fields = row.split(';')
        point, name, category = int(fields[0], 16), fields[1], fields[2]
        if name.endswith(', First>'):
            pending = (point, category)
        elif name.endswith(', Last>'):
            assert pending is not None and pending[1] == category
            result.append((pending[0], point, category))
            pending = None
        else:
            result.append((point, point, category))
    assert pending is None
    return result


def union(ranges, categories):
    merged = []
    for start, end, category in ranges:
        if not any(category.startswith(prefix) for prefix in categories):
            continue
        if merged and start <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(end, merged[-1][1]))
        else:
            merged.append((start, end))
    return merged


def escape(point):
    return f'\\u{point:04X}' if point <= 0xffff else f'\\u{{{point:X}}}'


def character_class(ranges):
    return ''.join(escape(start) if start == end else f'{escape(start)}-{escape(end)}' for start, end in ranges)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--unicode-data', type=Path, required=True)
    parser.add_argument('--unicode17-data', type=Path, required=True)
    args = parser.parse_args()
    data = args.unicode_data.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != EXPECTED_SHA256:
        raise ValueError(f'UnicodeData hash mismatch: {digest}')
    ranges = category_ranges(data.decode())
    data17 = args.unicode17_data.read_bytes()
    if hashlib.sha256(data17).hexdigest() != '2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c':
        raise ValueError('Unicode17 data hash mismatch')
    ranges17 = category_ranges(data17.decode())
    groups = {
        'UNICODE_16_LETTER_RANGES': ['L'],
        'UNICODE_16_NUMBER_RANGES': ['N'],
        'UNICODE_16_O200K_UPPER_RANGES': ['Lu', 'Lt', 'Lm', 'Lo', 'M'],
        'UNICODE_16_O200K_LOWER_RANGES': ['Ll', 'Lm', 'Lo', 'M'],
    }
    header = f'''// Generated by src/codegen/generateUnicodeProperties.py; do not edit.
// Regenerate with: python3 src/codegen/generateUnicodeProperties.py --unicode-data /path/UnicodeData-16.txt --unicode17-data /path/UnicodeData-17.txt
// Unicode 16.0.0 source: {SOURCE_URL}
// SHA-256: {digest}
// Native-class correction source: https://www.unicode.org/Public/17.0.0/ucd/UnicodeData.txt
// SHA-256: 2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c
// Unicode data: Copyright © 1991–2024 Unicode, Inc.; Unicode License V3.
// License: https://www.unicode.org/license.txt (data/Unicode-LICENSE.txt).
// Pinning the categories keeps tokenization independent of the JS engine's UCD.
'''
    output = header + '\n'.join(f'export const {name} = String.raw`{character_class(union(ranges, categories))}`\n' for name, categories in groups.items())
    guard_points = set()
    for name, categories in groups.items():
        old = {point for start, end in union(ranges, categories) for point in range(start, end + 1)}
        new = {point for start, end in union(ranges17, categories) for point in range(start, end + 1)}
        def points_to_ranges(points):
            result = []
            for point in sorted(points):
                if result and result[-1][1] + 1 == point:
                    result[-1] = (result[-1][0], point)
                else:
                    result.append((point, point))
            return result
        for point in old ^ new:
            guard_points.add(point if point <= 0xffff else 0xd800 + ((point - 0x10000) >> 10))
        for suffix, points in [('EXCLUDE', new - old), ('INCLUDE', old - new)]:
            output += f'export const {name.replace("UNICODE_16_", "UNICODE_17_TO_16_").replace("_RANGES", "_" + suffix + "_RANGES")} = String.raw`{character_class(points_to_ranges(points))}`\n\n'
    output += f'// Conservative UTF-16 prefilter: BMP changes plus affected astral lead surrogates.\nexport const UNICODE_17_TO_16_GUARD_RANGES = String.raw`{character_class(points_to_ranges(guard_points))}`\n'
    destination = Path(__file__).resolve().parents[1] / 'encodingParams' / 'unicode16Data.ts'
    destination.write_text(output)
    print(f'Wrote {destination} ({len(output)} bytes)')


if __name__ == '__main__':
    main()
