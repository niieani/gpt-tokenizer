#!/usr/bin/env python3
"""Publish the frozen optimization comparison; never runs measurements.

python3 benchmark/experiments/publish.py --prefix optimized-canonical --charts
Install benchmark/requirements-report.txt for --charts. Raw files are immutable;
all tables/charts are regenerated together after validation.
"""
import argparse
import importlib.util
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys

HERE = Path(__file__).resolve().parent
BENCH = HERE.parent
sys.path.insert(0, str(HERE))
import overview

spec = importlib.util.spec_from_file_location('legacy_report', HERE / 'legacy-report.py')
legacy = importlib.util.module_from_spec(spec)
spec.loader.exec_module(legacy)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--prefix', default='optimized-canonical')
    parser.add_argument('--charts', action='store_true')
    args = parser.parse_args()
    assert re.fullmatch(r'[a-zA-Z0-9_-]+', args.prefix), 'Invalid raw prefix'
    prefix = args.prefix
    build = None
    records = []
    writes = []
    report_jobs = []
    for suffix in ('node-o200k', 'node-cl100k', 'bun'):
        timing_path = BENCH / f'results/{prefix}-{suffix}.json'
        memory_path = BENCH / f'results/{prefix}-memory-{suffix}.json'
        timing = json.loads(timing_path.read_text())
        memory = json.loads(memory_path.read_text())
        cases = legacy.validate_timing(timing)
        legacy.validate_memory(memory, timing, timing_path, cases)
        expected = ({(p['id'], 'o200k_base') for p in timing['packages'] if 'o200k_base' in p['encodings']}
                    if suffix == 'node-o200k' else
                    {(id_, encoding) for id_ in ('gpt-tokenizer:local', 'gpt-tokenizer:npm')
                     for encoding in (('cl100k_base',) if suffix == 'node-cl100k' else ('cl100k_base', 'o200k_base'))})
        assert set(cases) == expected, 'Unexpected publication scope'
        assert timing['environment']['engine'] == ('bun' if suffix == 'bun' else 'node')
        if build is None:
            build = timing['candidateBuild']
        assert build == timing['candidateBuild'], 'Different builds cannot share one comparison'
        groups = legacy.summarize(timing, cases, memory)
        output = HERE / f'LEGACY-{suffix}-RESULTS.md'
        writes.append((output, f'<!-- Generated by benchmark/experiments/publish.py. -->\n\n[Raw timing](../results/{timing_path.name}) · [Raw settled memory](../results/{memory_path.name})\n\n' + legacy.render(timing, cases, groups, timing_path, memory, memory_path)))
        records.append((suffix, timing, memory, groups))
    real_paths = [BENCH / f'results/{prefix}-real-{suffix}.json' for suffix in ('node-o200k', 'node-cl100k', 'bun-o200k_base', 'bun-cl100k_base')]
    first_real = None
    for path in real_paths:
        run = json.loads(path.read_text())
        overview.validate(run)
        suffix = path.stem.removeprefix(prefix + '-real-')
        assert run['runtime']['bun'] == ('1.4.3' if suffix.startswith('bun-') else None)
        assert run['configuration']['encoding'] == ('cl100k_base' if 'cl100k' in suffix else 'o200k_base')
        assert run['configuration']['operations'] == ['encode', 'decode', 'count']
        assert run['configuration']['modes'] == ['repeated', 'stream']
        assert run['configuration']['legacy'] is False and run['configuration']['rounds'] == 5
        assert run['configuration']['warmMs'] >= 100
        assert run['configuration']['minMs'] >= (300 if path == real_paths[0] else 100)
        assert run['hardware']['hostname'] == records[0][1]['environment']['hostname']
        if first_real is None:
            first_real = run
        assert run['harness'] == first_real['harness'] and run['corpus'] == first_real['corpus']
        assert run['candidate']['files'] == build, 'Realistic build differs from legacy build'
        assert run['configuration']['consume'] == 'length', 'Do not mix API-return and full-output consumption metrics'
        expected_entries = {'baseline', 'candidate', 'ai-tokenizer', 'bpe-lite', '@goliapkg/tiktoken-wasm', 'tiktoken'} if path == real_paths[0] else {'baseline', 'candidate'}
        assert set(run['configuration']['entries']) == expected_entries, 'Unexpected realistic comparison scope'
        output = HERE / ('REALISTIC-' + path.stem.removeprefix(prefix + '-real-') + '-RESULTS.md')
        report_jobs.append(['vp', 'env', 'exec', '--node', '26.12.0', 'node', str(HERE / 'report.mjs'), str(path), str(output)])
    writes.append((HERE / 'OVERVIEW.md', '<!-- Generated by benchmark/experiments/overview.py through publish.py. -->\n\n' + overview.render(real_paths)))
    consumed_path = BENCH / f'results/{prefix}-consumed-node-o200k.json'
    assert consumed_path.exists(), 'Publication requires the complete-output decode diagnostic'
    if consumed_path.exists():
        consumed = json.loads(consumed_path.read_text())
        overview.validate(consumed)
        assert consumed['runtime']['bun'] is None
        assert consumed['configuration']['encoding'] == 'o200k_base'
        assert consumed['configuration']['modes'] == ['repeated', 'stream']
        assert consumed['configuration']['rounds'] == 5 and consumed['configuration']['legacy'] is False
        assert consumed['configuration']['warmMs'] >= 100 and consumed['configuration']['minMs'] >= 300
        assert consumed['hardware']['hostname'] == first_real['hardware']['hostname']
        assert consumed['harness'] == first_real['harness'] and consumed['corpus'] == first_real['corpus']
        assert consumed['candidate']['files'] == build
        assert consumed['configuration']['consume'] == 'full'
        assert consumed['configuration']['operations'] == ['decode']
        assert set(consumed['configuration']['entries']) == {'baseline', 'candidate', '@goliapkg/tiktoken-wasm', 'tiktoken'}
        report_jobs.append(['vp', 'env', 'exec', '--node', '26.12.0', 'node', str(HERE / 'report.mjs'), str(consumed_path), str(HERE / 'CONSUMED-node-o200k-RESULTS.md')])
        writes.append((HERE / 'CONSUMED-OVERVIEW-RESULTS.md', overview.render([consumed_path])))
    confirmation_links = []
    api_confirmation_paths = []
    for suffix in ('node-o200k', 'bun-o200k_base', 'bun-cl100k_base'):
        confirmation_path = BENCH / f'results/{prefix}-confirm-real-decode-{suffix}.json'
        if not confirmation_path.exists():
            continue
        original = json.loads((BENCH / f'results/{prefix}-real-{suffix}.json').read_text())
        confirmation = json.loads(confirmation_path.read_text())
        overview.validate(confirmation)
        scope = confirmation['configuration']
        assert scope['encoding'] == original['configuration']['encoding'] and scope['consume'] == 'length'
        assert scope['operations'] == ['decode'] and scope['modes'] == ['repeated', 'stream']
        assert scope['entries'] == (['baseline', 'candidate', 'ai-tokenizer'] if suffix == 'node-o200k' else ['baseline', 'candidate'])
        assert scope['rounds'] == 5 and scope['legacy'] is False
        assert scope['warmMs'] >= 500 and scope['minMs'] >= 500
        assert confirmation['runtime'] == original['runtime']
        assert confirmation['candidate']['files'] == build
        assert confirmation['harness'] == original['harness'] and confirmation['corpus'] == original['corpus']
        assert confirmation['baseline'] == original['baseline']
        assert all(original['packages'][key] == value for key, value in confirmation['packages'].items())
        assert confirmation['hardware']['hostname'] == original['hardware']['hostname']
        api_confirmation_paths.append(confirmation_path)
        report_jobs.append(['vp', 'env', 'exec', '--node', '26.12.0', 'node', str(HERE / 'report.mjs'), str(confirmation_path), str(HERE / f'CONFIRM-REAL-DECODE-{suffix}-RESULTS.md')])
    if api_confirmation_paths:
        writes.append((HERE / 'CONFIRM-REAL-DECODE-OVERVIEW-RESULTS.md', overview.render(api_confirmation_paths)))
        confirmation_links.append('[Realistic API-return decode confirmations](experiments/CONFIRM-REAL-DECODE-OVERVIEW-RESULTS.md)')
    confirmation_path = BENCH / f'results/{prefix}-confirm-consumed-node-o200k.json'
    if confirmation_path.exists():
        assert consumed_path.exists(), 'Confirmation requires its original comparison'
        confirmation = json.loads(confirmation_path.read_text())
        overview.validate(confirmation)
        for field in ('entries', 'operations', 'modes', 'encoding', 'consume', 'rounds', 'legacy'):
            assert confirmation['configuration'][field] == consumed['configuration'][field], 'Changed confirmation scope'
        assert confirmation['configuration']['warmMs'] >= 500 and confirmation['configuration']['minMs'] >= 500
        assert confirmation['runtime'] == consumed['runtime']
        assert confirmation['candidate']['files'] == build
        assert confirmation['harness'] == consumed['harness'] and confirmation['corpus'] == consumed['corpus']
        assert confirmation['baseline'] == consumed['baseline'] and confirmation['packages'] == consumed['packages']
        assert confirmation['hardware']['hostname'] == consumed['hardware']['hostname']
        writes.append((HERE / 'CONFIRM-CONSUMED-OVERVIEW-RESULTS.md', overview.render([confirmation_path])))
        report_jobs.append(['vp', 'env', 'exec', '--node', '26.12.0', 'node', str(HERE / 'report.mjs'), str(confirmation_path), str(HERE / 'CONFIRM-CONSUMED-node-o200k-RESULTS.md')])
        confirmation_links.append('[Decode-and-read confirmation](experiments/CONFIRM-CONSUMED-OVERVIEW-RESULTS.md)')
    for encoding in ('o200k_base', 'cl100k_base'):
        suffix = 'node-o200k' if encoding == 'o200k_base' else 'node-cl100k'
        confirmation_path = BENCH / f'results/{prefix}-confirm-{suffix}.json'
        if not confirmation_path.exists():
            continue
        confirmation = json.loads(confirmation_path.read_text())
        cases = legacy.validate_timing(confirmation)
        assert set(cases) == {(id_, encoding) for id_ in ('gpt-tokenizer:local', 'gpt-tokenizer:npm')}
        assert confirmation['environment']['engine'] == 'node'
        assert confirmation['environment']['engineVersion'] == '26.12.0'
        assert confirmation['environment']['hostname'] == records[0][1]['environment']['hostname']
        assert confirmation['candidateBuild'] == build
        original = records[0 if encoding == 'o200k_base' else 1][1]
        assert confirmation['inputs'] == original['inputs'] and confirmation['packages'] == original['packages']
        assert confirmation['settings']['warmupMs'] >= 500 and confirmation['settings']['minMs'] >= 500
        groups = legacy.summarize(confirmation, cases, None)
        writes.append((HERE / f'CONFIRM-LEGACY-{suffix}-RESULTS.md', legacy.render(confirmation, cases, groups, confirmation_path, None, None)))
        confirmation_links.append(f'[Node/{encoding} original-case confirmation](experiments/CONFIRM-LEGACY-{suffix}-RESULTS.md)')
    primary = records[0]
    timing, memory, rows = primary[1], primary[2], primary[3]['o200k_base']
    local = next(row for row in rows if row['id'] == 'gpt-tokenizer:local')
    release = next(row for row in rows if row['id'] == 'gpt-tokenizer:npm')
    env = timing['environment']
    lines = ['<!-- Generated by benchmark/experiments/publish.py. -->', '', '# Optimized benchmark results', '',
             'Primary target: **Node 26.12.0 / o200k_base**. Bun 1.4.3 and cl100k are release-regression checks. All tables use five fresh processes; ranges are full process minimum–maximum, not confidence intervals. Ranks exclude the historical npm release.', '',
             '**The legacy arithmetic mean is dominated by two large synthetic inputs. It does not establish a universal winner.** Realistic categories and repeated/32-variant modes stand separately in the [overview](experiments/OVERVIEW.md); every per-document median loss is listed there. The [interpretation](OPTIMIZED-FINDINGS.md) discusses losses and tradeoffs.', '',
             f"Host: {env['hostname']}, {len(env['cpus'])} vCPUs presenting {env['cpus'][0]['model']}, {env['totalMemoryGiB']:.2f} GiB; {env['platform']}/{env['arch']}, kernel {env['kernel']}. KVM VM, no CPU pinning/frequency control. The queue prevents our jobs from overlapping; shared-host scheduling, turbo, JIT and GC remain uncontrolled.", '',
             '## Node/o200k legacy target', '',
             '| Case | Checkout median [min,max] | Rank | npm 4.0.3 median [min,max] |', '|---|---:|---:|---:|']
    metrics = [('encode', 'Encode ms/call'), ('decode', 'Decode API-return ms/call (length only)'), ('count', 'Count ms/call'), ('load', 'Import + construction ms'), ('init_heapUsed', 'Settled init heap delta MiB'), ('init_rss', 'Settled init RSS delta MiB'), ('retained_heapUsed', 'One-pass retained heap growth MiB'), ('retained_rss', 'One-pass retained RSS growth MiB'), ('final_heapUsed', 'Absolute final heap MiB'), ('final_rss', 'Absolute final RSS MiB'), ('peak_rss', 'One-pass process peak RSS MiB')]
    for metric, label in metrics:
        a, b = local['metrics'][metric], release['metrics'][metric]
        fmt = lambda value: f"{value['median']:.3f} [{value['min']:.3f}, {value['max']:.3f}]"
        lines.append(f"| {label} | {fmt(a)} | {a['rank']} | {fmt(b)} |")
    lines += ['', 'Encoding/decoding/counting use the original seven-input mean per process. Load excludes process startup. Memory is a separate settled one-pass phase, including byte-heavy decode; final/peak RSS include harness/corpus. See [all contenders and every input](experiments/LEGACY-node-o200k-RESULTS.md).', '', '## Informational release comparisons', '',
              'These selected runs compare the checkout with npm 4.0.3 only; they do not re-rank other competitors. Values below are legacy mean latency ratios: npm / checkout, so above 1 is a speedup. The linked tables include absolute latencies, load, and matching memory.', '',
              '| Engine / encoding | Encode speedup | Decode speedup | Count speedup | Detailed evidence |', '|---|---:|---:|---:|---|']
    for suffix, run, _, groups in records[1:]:
        for encoding, group in groups.items():
            candidate = next(row for row in group if row['id'] == 'gpt-tokenizer:local')
            baseline = next(row for row in group if row['id'] == 'gpt-tokenizer:npm')
            ratios = [baseline['metrics'][op]['median'] / candidate['metrics'][op]['median'] for op in ('encode', 'decode', 'count')]
            lines.append(f"| {run['environment']['engine']} / {encoding} | {ratios[0]:.3f}× | {ratios[1]:.3f}× | {ratios[2]:.3f}× | [Timing and memory](experiments/LEGACY-{suffix}-RESULTS.md) |")
    if consumed_path.exists():
        lines += ['', '## Decode and read all output', '', 'API-return timings read only result length and can leave decoded strings as lazy ropes. The [separate consumed-output comparison](experiments/CONSUMED-OVERVIEW-RESULTS.md) includes a checksum over every returned code unit, with [full absolute tables](experiments/CONSUMED-node-o200k-RESULTS.md). It measures decode plus the common consumer cost and is not pooled with API-return ranks.', '']
    if confirmation_links:
        lines += ['', '## Longer confirmations', '', 'Five new processes per entry, at least 500 ms warmup and 500 ms measurement per cell. Original runs remain unchanged; different budgets are not pooled.', '']
        lines += ['- ' + link for link in confirmation_links]
    lines += ['', '## Correctness, versions, and reproduction', '']
    for engine in ('node', 'bun'):
        path = BENCH / f'results/{prefix}-verified-correctness-{engine}.json'
        if not path.exists():
            path = BENCH / f'results/{prefix}-correctness-{engine}.json'
        gate = json.loads(path.read_text())
        assert gate['passed'] is True and gate['failureCount'] == 0 and not gate['failures']
        assert gate['candidate']['files'] == build, 'Correctness gate executed a different build'
        assert gate['runtime']['bun'] == ('1.4.3' if engine == 'bun' else None)
        if engine == 'node':
            assert gate['runtime']['version'] == 'v26.12.0'
        assert gate['harnessSha256'] == hashlib.sha256((HERE / 'correctness.mjs').read_bytes()).hexdigest(), 'Stale correctness harness'
        assert {row['encoding'] for row in gate['results']} == {'cl100k_base', 'o200k_base'}
        assert all(row['strings'] >= 4984 and row['validIdSequences'] == 350 for row in gate['results'])
        counts = ', '.join(f"{row['encoding']}: {row['strings']} strings + {row['validIdSequences']} valid-ID sequences" for row in gate['results'])
        lines.append(f'- [{engine} expanded gate](results/{path.name}): zero failures; {counts}; seed `{gate["seed"]}`.')
    lines += ['', '| Package | Version |', '|---|---|']
    lines += [f"| {p['id']} | {p['version']} |" for p in timing['packages']]
    lines += ['', 'Every timed input matches independent token IDs/round trips/counts. Additional semantic-probe failures are retained in the overview and full reports; timed-input correctness does not imply universal API equivalence. [Selection/skips](README.md), [audit](AUDIT.md), and [optimization tradeoffs and rejected work](OPTIMIZATIONS.md) provide context.', '',
              f"Executed build manifest SHA-256: `{overview.digest(build)}`. Primary source commit `{env['gitCommit']}`. Each linked report lists raw SHA-256, source/runtime/hardware, input hashes and actual budgets. Matching built modules are required across every final phase.", '',
              f'Build and measure with `GPT_BENCH_CONFIRM=1 bash benchmark/experiments/reproduce.sh NEW_PREFIX`; omit the environment flag for first comparisons without longer confirmations. Regenerate these artifacts with `python3 benchmark/experiments/publish.py --prefix {prefix} --charts` after installing `benchmark/requirements-report.txt`. Historical pre-optimization [full engine/contender matrix](RESULTS.md) remains unchanged.', '']
    writes.append((BENCH / 'OPTIMIZED-RESULTS.md', '\n'.join(lines)))
    # All raw scopes, correctness gates and executed builds passed before any
    # publication output is touched. Never publish a partial run as a ranking.
    for job in report_jobs:
        subprocess.run(job, check=True)
    for output, text in writes:
        output.write_text(text)
    if args.charts:
        subprocess.run([sys.executable, str(HERE / 'summary-chart.py'), str(BENCH / f'results/{prefix}-node-o200k.json')], check=True)
        subprocess.run([sys.executable, str(HERE / 'charts.py'), str(BENCH / f'results/{prefix}-node-o200k.json'), str(BENCH / f'results/{prefix}-memory-node-o200k.json'), str(real_paths[0]), str(BENCH.parent / 'docs')], check=True)


if __name__ == '__main__':
    main()
