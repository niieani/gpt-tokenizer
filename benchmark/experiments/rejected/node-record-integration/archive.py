"""Validate immutable experiment evidence and regenerate descriptive archive tables."""
import hashlib
import json
from pathlib import Path
from statistics import median

ROOT = Path(__file__).resolve().parent


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def regenerate():
    pilot = json.loads((ROOT / 'pilot-v3.json').read_text())
    assert pilot['complete'] and pilot['corpus']['version'] == 3
    assert pilot['sources']['driverSHA256'] == sha(ROOT / 'run.mjs')
    assert pilot['sources']['workerSHA256'] == sha(ROOT / 'worker.mjs')
    candidate = pilot['sources']['candidateFiles']['BytePairEncodingCore.js']
    frozen = pilot['sources']['frozenFiles']['BytePairEncodingCore.js']
    lines = ['<!-- Generated by archive.py; regenerate: python3 benchmark/experiments/rejected/node-record-integration/archive.py -->',
             '', '# Rejected engine-selected Record: sustained cache churn', '',
             'Two fresh processes per entry/engine/encoding, opposite order. 500,000 distinct eight-letter pieces in 500-piece blocks; '
             '100,000-entry cache. The fill phase precedes four 100,000-piece churn phases. '
             'Each encode is followed immediately by count on the same block, so count measures hits warmed by encode. '
             'Timings include the public method and result allocation; exact token checks occur outside timing. '
             'Encode and count remain separate metrics. The combined time improves on Node, but does not cancel count regressions.', '',
             '| Encoding | Engine | Phase | Operation | Frozen ms [range] | Candidate ms [range] | Paired speedup [range] | Candidate added µs/block |',
             '|---|---|---|---|---:|---:|---:|---:|']
    for suffix in ['o200', 'cl100']:
        raw = json.loads((ROOT / f'churn-{suffix}.json').read_text())
        assert raw['complete'] and raw['rounds'] == 2 and len(raw['rows']) == 8
        assert raw['scriptSHA256'] == sha(ROOT / 'churn.mjs')
        assert raw['oracleSHA256'] == json.loads((ROOT / f'churn-{suffix}-oracle.json').read_text())['sha256']
        assert raw['candidateSourceSHA256'] == pilot['sources']['candidateCoreSourceSHA256']
        assert raw['sourceCommits']['candidate'] == pilot['sources']['candidateCommit']
        for row in raw['rows']:
            assert row['exactTokens'] and row['bounded'] and len(row['phases']) == 5
            assert row['coreSHA256'] == (candidate if row['variant'] == 'candidate' else frozen)
            assert row['runtime']['bun'] == '1.4.3' or row['runtime']['node'] == 'v26.12.0'
            assert row['storage'] == ('record' if row['variant'] == 'candidate' and row['runtime']['bun'] is None else 'map')
        for bun in [None, '1.4.3']:
            rows = {(row['variant'], row['round']): row for row in raw['rows'] if row['runtime']['bun'] == bun}
            assert len(rows) == 4
            for phase, indices in [('fill', [0]), ('sustained churn', [1, 2, 3, 4])]:
                for operation in ['encode', 'count']:
                    sums = {entry: [sum(rows[entry, r]['phases'][i][operation + 'Ms'] for i in indices) for r in range(2)] for entry in ['candidate', 'frozen']}
                    c, f = sums['candidate'], sums['frozen']
                    ratios = [f[r]/c[r] for r in range(2)]
                    blocks = len(indices)*raw['capacity']/raw['blockSize']
                    delta = median([(c[r]-f[r])*1000/blocks for r in range(2)])
                    engine = 'Bun1.4.3' if bun else 'Node26.12.0'
                    lines.append(f"| {raw['encoding']} | {engine} | {phase} | {operation} | {median(f):.2f} [{min(f):.2f}, {max(f):.2f}] | {median(c):.2f} [{min(c):.2f}, {max(c):.2f}] | {median(ratios):.3f}× [{min(ratios):.3f}, {max(ratios):.3f}] | {delta:+.2f} |")
    for engine in ['node', 'bun']:
        gate = json.loads((ROOT / f'correctness-{engine}.json').read_text())
        assert gate['passed'] and gate['failureCount'] == 0
        assert gate['candidate']['files']['BytePairEncodingCore.js'] == candidate
        assert all(row['strings'] == 4984 and row['validIdSequences'] == 350 for row in gate['results'])
    (ROOT / 'CHURN-RESULTS.md').write_text('\n'.join(lines) + '\n')
    manifest = {key: pilot[key] for key in ['runtime', 'hardware', 'corpus', 'sources']}
    manifest['evidenceSHA256'] = {name: sha(ROOT / name) for name in ['candidate.patch', 'pilot-v3.json', 'churn-o200.json', 'churn-cl100.json', 'correctness-node.json', 'correctness-bun.json', 'run.mjs', 'worker.mjs', 'churn.mjs', 'build.log', 'tests.log', 'churn-o200-oracle.json', 'churn-cl100-oracle.json']}
    manifest['generatedBy'] = 'python3 benchmark/experiments/rejected/node-record-integration/archive.py'
    (ROOT / 'source-manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')


if __name__ == '__main__':
    regenerate()
