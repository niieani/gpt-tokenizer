"""Scoped diagnostic report. References never participate in contender ranks."""
import collections, hashlib, json, math, statistics, sys
from pathlib import Path
raw_path, output = map(Path, sys.argv[1:3])
r = json.loads(raw_path.read_text())
c = r['configuration']
assert r['complete'] is True and not r['exploratory']
assert c['rounds'] >= 5 and c['minMs'] >= 300 and c['warmMs'] >= 100
assert r['runtime']['version'] == 'v26.12.0' and r['runtime']['bun'] is None
refs = {'baseline', 'gpt-tokenizer:npm'}
pure = ['candidate', 'ai-tokenizer', 'bpe-lite']
contenders = pure + ['@goliapkg/tiktoken-wasm']
assert set(c['entries']) == refs | set(contenders)
assert r['baseline']['kind'] == 'frozen local build'
assert len(r['baseline']['files']) > 0 and len(r['candidate']['files']) > 0
for values in [r['baseline']['files'], r['candidate']['files'], r['harness']]:
    assert all(len(v) == 64 and all(ch in '0123456789abcdef' for ch in v) for v in values.values())
assert len(r['samples']) == c['rounds'] * len(c['entries'])
idx = {}
for entry in c['entries']:
    samples = [s for s in r['samples'] if s['entry'] == entry]
    assert len(samples) == c['rounds']
    assert {s['round'] for s in samples} == set(range(c['rounds']))
    for s in samples:
        assert s['verification']['passed'] and s['verification']['documents'] == len(r['corpus']['documents'])
        assert s['verification']['inputs'] == sum(1 + len(d['streamSha256']) for d in r['corpus']['documents'])
        assert s['runtime']['node'] == 'v26.12.0' and s['runtime']['bun'] is None
        assert math.isfinite(s['checksum'])
        assert len(s['measurements']) == len(r['corpus']['documents']) * len(c['operations']) * len(c['modes'])
        for m in s['measurements']:
            assert m['warmup']['calls'] >= c['warmCalls'] and m['warmup']['elapsedMs'] >= c['warmMs']
            assert m['elapsedMs'] >= c['minMs'] and m['calls'] >= 5
            assert m['ms'] > 0 and abs(m['elapsedMs'] / m['calls'] - m['ms']) < 1e-9
            key = entry, s['round'], m['id'], m['mode'], m['operation']
            assert key not in idx
            idx[key] = m['ms']
def series(entry, doc, mode, op):
    return [idx[entry, i, doc, mode, op] for i in range(c['rounds'])]
def median(entry, doc, mode, op):
    return statistics.median(series(entry, doc, mode, op))
def gm(v):
    return math.exp(sum(math.log(x) for x in v) / len(v))
def ranged(values, digits=4):
    return f'{statistics.median(values):.{digits}f} [{min(values):.{digits}f}, {max(values):.{digits}f}]'
lines = ['# Unified-record Node/o200k confirmation', '',
    'Generated by report.py from complete frozen raw data; do not edit tables.', '',
    'Five fresh processes per entry; 100ms warmup and 300ms measurement per document/mode/operation, >=20 warmup calls. Node26.12.0; o200k_base. Output consumer reads result length. Historical corpus v2; no pooling with its privacy replacement. Ranges are process minima/maxima, not confidence intervals.', '',
    'Frozen current build and npm4.0.3 are references and excluded from every rank. Pure-JS ranks cover only candidate/ai-tokenizer/bpe-lite; overall ranks add Golia WASM. These are scoped descriptive ranks, not universal leadership claims; overlapping ranges need caution.', '',
    'Raw SHA256: `' + hashlib.sha256(raw_path.read_bytes()).hexdigest() + '`.',
    'Corpus JSON SHA256: `' + r['corpus']['sha256'] + '`.', '',
    '## Short-input guard and resource tradeoff', '',
    '| Document | Mode | Operation | Frozen/candidate ratio: median [min, max] |',
    '| --- | --- | --- | ---: |']
for doc in ['support', 'european', 'readme.md']:
    for mode in c['modes']:
        for op in c['operations']:
            a, b = series('baseline', doc, mode, op), series('candidate', doc, mode, op)
            lines.append(f'| {doc} | {mode} | {op} | {ranged([x/y for x,y in zip(a,b)],3)} |')
lines += ['', 'Ratio >1 favors the candidate; <1 is a regression. These per-document guards remain visible alongside category averages.', '',
    '| Entry | Initialization ms | Settled initialization heap MiB | Settled initialization RSS MiB | After-first-pass RSS MiB |',
    '| --- | ---: | ---: | ---: | ---: |']
for entry in c['entries']:
    ss = [s for s in r['samples'] if s['entry'] == entry]
    fields = [[s['initializationMs'] for s in ss], [s['initialized']['heapUsed']/1048576 for s in ss], [s['initialized']['rss']/1048576 for s in ss], [s['afterFirstPass']['rss']/1048576 for s in ss]]
    lines.append('| ' + entry + ' | ' + ' | '.join(ranged(v,2) for v in fields) + ' |')
lines += ['', 'Memory is a phase-specific fresh-process diagnostic, not a final settled warm-traffic or peak-memory claim. Initialization includes import and table construction. It is intentionally reported with latency rather than hidden by throughput gains.', '', '## Category comparisons', '',
    'For each process, category latency is the geometric mean of equally weighted document latencies. Cells show its median [min, max] in milliseconds. Ranks compare those medians only.', '',
    '| Category | Mode | Operation | Candidate | ai-tokenizer | bpe-lite | Golia | Candidate JS rank | Candidate overall rank |',
    '| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |']
for category in dict.fromkeys(d['category'] for d in r['corpus']['documents']):
    docs = [d['id'] for d in r['corpus']['documents'] if d['category'] == category]
    for mode in c['modes']:
        for op in c['operations']:
            values = {e:[gm([idx[e,i,d,mode,op] for d in docs]) for i in range(c['rounds'])] for e in contenders}
            med = {e:statistics.median(v) for e,v in values.items()}
            jsrank = 1 + sum(med[e] < med['candidate'] for e in pure if e != 'candidate')
            rank = 1 + sum(med[e] < med['candidate'] for e in contenders if e != 'candidate')
            lines.append('| ' + ' | '.join([category,mode,op]+[ranged(values[e]) for e in contenders]+[f'{jsrank}/3',f'{rank}/4']) + ' |')
lines += ['', '## Every document and reference', '',
    '| Document | Mode | Operation | Frozen | Candidate | npm reference | ai-tokenizer | bpe-lite | Golia |',
    '| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |']
for d in r['corpus']['documents']:
    for mode in c['modes']:
        for op in c['operations']:
            entries = ['baseline','candidate','gpt-tokenizer:npm','ai-tokenizer','bpe-lite','@goliapkg/tiktoken-wasm']
            lines.append('| ' + ' | '.join([d['id'],mode,op]+[ranged(series(e,d['id'],mode,op)) for e in entries]) + ' |')
lines += ['', '## Semantic probes', '',
    'Every measured document and all stream variants passed reference ID/count/round-trip checks. The separate boundary probes may expose known disagreements with the JS tiktoken oracle; they are not silently treated as equivalent inputs.', '']
failures = collections.defaultdict(set)
for s in r['samples']:
    for p in s['semanticProbes']:
        if p.get('error') or not all(p.get(k,False) for k in ['ids','roundTrip','count']):
            failures[s['entry']].add(json.dumps(p,ensure_ascii=True,sort_keys=True))
if failures:
    for entry, probes in failures.items():
        lines.append('- ' + entry + ': `' + '; '.join(sorted(probes)) + '`')
else:
    lines.append('No boundary probe disagreements observed.')
Path(output).write_text('\n'.join(lines)+'\n')
